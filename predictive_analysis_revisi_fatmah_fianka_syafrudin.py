# Standarisasi data
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

X_train

"""## Modelling

### Logistic Regression
Logistic Regression adalah algoritma klasifikasi yang digunakan untuk memprediksi probabilitas kejadian suatu peristiwa. Model ini menggunakan fungsi sigmoid untuk memetakan input numerik menjadi nilai probabilitas antara 0 dan 1. Meskipun disebut "regression," algoritma ini digunakan untuk tugas klasifikasi biner dan dapat diperluas ke klasifikasi multikelas.
"""

from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix, classification_report

log_reg = LogisticRegression()
log_reg.fit(X_train, y_train)
log_reg_pred = log_reg.predict(X_test)

print(classification_report(y_test, log_reg_pred))

print("Akurasi : {:.2f}".format(accuracy_score(y_test, log_reg_pred)))

"""#### Grid Search Logistic Regression"""

from sklearn.model_selection import GridSearchCV
# Menentukan kombinasi hyperparameter untuk diuji pada Logistic Regression
parameter_logreg = {
    'C': [0.001, 0.01, 0.1, 1, 10],
    'solver': ['liblinear', 'newton-cg', 'lbfgs', 'sag', 'saga']
}

# Melakukan pencarian grid terbaik menggunakan validasi silang
grid_lr = GridSearchCV(estimator=log_reg, param_grid=parameter_logreg,
                       cv=5, scoring='accuracy', verbose=1)
grid_lr.fit(X_train, y_train)

# Menampilkan kombinasi parameter terbaik
optimal_params = grid_lr.best_params_
print("Hyperparameter Terbaik:", optimal_params)

# Menyimpan model dengan performa terbaik dari hasil grid search
optimal_model = grid_lr.best_estimator_

# Prediksi menggunakan model terbaik
y_pred_optimal = optimal_model.predict(X_test)

# Evaluasi akurasi model terbaik
best_acc = accuracy_score(y_test, y_pred_optimal)
print(f"Akurasi Model Terbaik: {best_acc:.2f}")

"""### KNN
KNN adalah algoritma non-parametrik yang digunakan untuk klasifikasi dan regresi. Model ini menentukan kelas atau nilai dari suatu data baru berdasarkan mayoritas kelas atau rata-rata nilai dari 'k' tetangga terdekatnya dalam ruang fitur.
"""

from sklearn.neighbors import KNeighborsClassifier
# Memilih 5 nilai K secara acak
