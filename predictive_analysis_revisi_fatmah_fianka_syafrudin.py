def drop_anomaly(df):
    anomaly = ['Glucose', 'BloodPressure', 'BMI']
    Q1 = df[anomaly].quantile(0.25)
    Q3 = df[anomaly].quantile(0.75)
    IQR = Q3 - Q1

    # Hanya menghilangkan bagian bawah yang bernilai 0
    min = Q1 - (IQR * 1.5)
    lower_array = np.where(df[anomaly] <= min)[0]
    df.drop(index=lower_array, inplace=True)
    return df

