"""#### Elbow Method"""

from sklearn.metrics import accuracy_score
# Menghitung nilai optimal K dengan Elbow Method
error_rate = []

# Uji performa KNN untuk nilai K dari 1 sampai 7
for k in range(1, 8):
    model_knn = KNeighborsClassifier(n_neighbors=k)
    model_knn.fit(X_train, y_train)

    prediksi = model_knn.predict(X_test)
    akurasi = accuracy_score(y_test, prediksi)

    print(f"K = {k} -> Akurasi: {akurasi:.2f}")

    # Hitung error rate sebagai proporsi prediksi salah
    kesalahan = np.mean(prediksi != y_test)
    error_rate.append(kesalahan)

plt.figure(figsize=(8,5))
plt.plot(range(1, 8), error_rate, color='blue', linestyle='dashed', marker='o', markerfacecolor='red', markersize=10)
plt.title('Perbandingan Error Rate terhadap K', fontsize=15)
plt.xlabel('Nilai K')
plt.ylabel('')
plt.show()

# Memilih error rate terkecil
print("Minimum error:",min(error_rate)," terdapat pada K = ",error_rate.index(min(error_rate))+1)

